const assert = require('node:assert/strict');
const fs = require('node:fs'), path = require('node:path'), {pathToFileURL} = require('node:url');
const {chromium} = require('playwright');
(async () => {
  const browser = await chromium.launch({headless:true, channel:'chromium', args:['--no-sandbox']});
  const file = pathToFileURL(path.resolve(__dirname, '../dist/OpenEmergencyHandbook-offline.html')).href;
  const external = [], errors = [];
  const context = await browser.newContext({viewport:{width:390,height:844}});
  await context.route(/^https?:/, route => { external.push(route.request().url()); return route.abort(); });
  const page = await context.newPage(); page.on('pageerror', error => errors.push(error.message));
  await page.goto(file);
  assert.equal(await page.locator('article:visible').count(),30);
  await page.locator('#search').fill('blackot');
  assert.match(await page.locator('#count').innerText(), /possible matches/);
  assert.equal(await page.locator('article:visible').first().getAttribute('id'),'en-power');
  await page.locator('#category').selectOption('aid');
  assert(await page.locator('#empty').isVisible());
  await page.locator('#reset').click(); assert.equal(await page.locator('article:visible').count(),30);
  await page.locator('#de').click(); await page.locator('#search').fill('bleeding');
  assert.equal(await page.locator('article:visible').first().getAttribute('id'),'de-bleeding');
  await page.locator('#clear').click();
  await page.evaluate(() => { location.hash = '#en-fallout'; });
  await page.waitForFunction(() => document.documentElement.lang === 'en');
  await page.locator('#en-fallout nav a[href="#en-water"]').click();
  assert(await page.locator('#en-water').isVisible()); assert.equal(await page.locator('#search').inputValue(),'');
  await page.goto(file); await page.screenshot({path:path.resolve(__dirname,'../dist/HTML-preview.png')});
  await page.setViewportSize({width:320,height:640});
  await page.addStyleTag({content:'body {font-size:36px}'});
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Large-text horizontal overflow');
  await page.screenshot({path:path.resolve(__dirname,'../dist/HTML-large-text.png')});
  const nojs = await browser.newContext({javaScriptEnabled:false,viewport:{width:390,height:844}});
  await nojs.route(/^https?:/, route => { external.push(route.request().url()); return route.abort(); });
  const plain = await nojs.newPage(); await plain.goto(file);
  assert.equal(await plain.locator('article:visible').count(),60);
  assert(!(await plain.locator('.interactive').isVisible()));
  await plain.locator('#contents-de-water a').click();
  assert(await plain.locator('#de-water h2').isVisible());
  await plain.locator('#de-water details summary').click();
  assert(await plain.locator('#de-water details a').first().isVisible());
  await plain.screenshot({path:path.resolve(__dirname,'../dist/HTML-no-script.png')});
  assert.deepEqual(errors,[]); assert.deepEqual(external,[]);
  fs.writeFileSync(path.resolve(__dirname,'../dist/HTML-TESTS.json'),JSON.stringify({engine:'Chromium',javascript:'ranked bilingual/typo search, category reset, related anchors, 200% CSS text',no_javascript:'60 guides, native anchors and source disclosures',external_requests:external.length,page_errors:errors.length},null,2)+'\n');
  await browser.close(); console.log('Offline browser checks passed with and without JavaScript; no external requests or page errors');
})().catch(error => { console.error(error); process.exit(1); });
